# Builds scripts/faces.js: small profile photos for the 40 sample members in scripts/seed.js, in the same order.
# The faces are AI-generated portraits from the Amie project (amie_faces/), so none of them is a real person.
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts/make-faces.ps1
Add-Type -AssemblyName System.Drawing
$app = Split-Path -Parent $PSScriptRoot
$src = Join-Path (Split-Path -Parent (Split-Path -Parent $app)) 'amie_faces'
$manifest = Get-Content (Join-Path $src 'manifest.json') -Raw -Encoding UTF8 | ConvertFrom-Json
# one entry per seed name, in order: Jordan Park, Priya Raman, Dev Malhotra, ...
$who = @('east_asian/male', 'south_asian/female', 'south_asian/male', 'black/male', 'east_asian/female', 'east_asian/female', 'latino/male', 'black/female', 'white/male', 'white/female',
  'east_asian/male', 'white/female', 'middle_eastern/male', 'east_asian/female', 'latino/male', 'south_asian/female', 'white/male', 'east_asian/female', 'black/male', 'latino/female',
  'south_asian/male', 'white/female', 'white/male', 'south_asian/female', 'white/male', 'middle_eastern/female', 'white/male', 'south_asian/female', 'white/male', 'white/female',
  'black/male', 'black/female', 'south_asian/male', 'white/female', 'latino/male', 'latino/female', 'white/male', 'white/female', 'white/male', 'black/female')
$codec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object { $_.MimeType -eq 'image/jpeg' }
$params = New-Object System.Drawing.Imaging.EncoderParameters 1
$params.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter ([System.Drawing.Imaging.Encoder]::Quality, [long]78)
$used = @{}; $out = New-Object System.Collections.Generic.List[string]
foreach ($g in $who) {
  $race, $sex = $g.Split('/')
  $pick = $manifest | Where-Object { $_.race -eq $race -and $_.sex -eq $sex -and ($_.age_band -eq 'A_20s' -or $_.age_band -eq 'B_30s') -and -not $used[$_.file] } | Sort-Object age_band, file | Select-Object -First 1
  $used[$pick.file] = $true
  $img = [System.Drawing.Image]::FromFile((Join-Path $src $pick.file))
  $side = [Math]::Min($img.Width, $img.Height)
  $bmp = New-Object System.Drawing.Bitmap 200, 200
  $gr = [System.Drawing.Graphics]::FromImage($bmp)
  $gr.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
  $gr.DrawImage($img, (New-Object System.Drawing.Rectangle 0, 0, 200, 200), [int](($img.Width - $side) / 2), [int](($img.Height - $side) / 4), $side, $side, [System.Drawing.GraphicsUnit]::Pixel)
  $ms = New-Object System.IO.MemoryStream
  $bmp.Save($ms, $codec, $params)
  $out.Add([Convert]::ToBase64String($ms.ToArray()))
  $ms.Dispose(); $gr.Dispose(); $bmp.Dispose(); $img.Dispose()
}
$js = "// Generated by scripts/make-faces.ps1: AI-generated sample faces (no real people), one per name in scripts/seed.js.`n'use strict';`nmodule.exports = [`n" + (($out | ForEach-Object { "  '" + $_ + "'" }) -join ",`n") + "`n];`n"
[System.IO.File]::WriteAllText((Join-Path $app 'scripts\faces.js'), $js, (New-Object System.Text.UTF8Encoding $false))
'faces.js: {0} faces, {1:N0} KB' -f $out.Count, ((Get-Item (Join-Path $app 'scripts\faces.js')).Length / 1KB)
